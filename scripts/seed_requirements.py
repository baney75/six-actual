#!/usr/bin/env python3
"""Seed or refresh REQUIREMENTS.md from the section F tables in docs/BRIEF.md.

Existing status and evidence are kept. New IDs start as `todo`.
`--check` exits non-zero when REQUIREMENTS.md is missing an ID from the brief,
lists an ID the brief does not have, or marks a row verified without evidence.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BRIEF = ROOT / "docs" / "BRIEF.md"
REQS = ROOT / "REQUIREMENTS.md"
ROW = re.compile(r"^\|\s*([A-Z]+-\d{2})\s*\|(.*)$")


def brief_rows() -> list[tuple[str, str, str]]:
    text = BRIEF.read_text(encoding="utf-8")
    start = text.index("## F. Requirements catalog")
    end = text.index("## G. Verification suite")
    rows = []
    for line in text[start:end].splitlines():
        m = ROW.match(line)
        if not m:
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        rows.append((cells[0], cells[1], cells[2]))
    return rows


def existing() -> dict[str, tuple[str, str]]:
    out: dict[str, tuple[str, str]] = {}
    if not REQS.exists():
        return out
    for line in REQS.read_text(encoding="utf-8").splitlines():
        m = ROW.match(line)
        if not m:
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        # | ID | Requirement | Verifier | Status | Evidence |  (new layout)
        # | ID | Requirement | Status | Evidence |             (old layout)
        if len(cells) >= 5:
            out[cells[0]] = (cells[3], cells[4])
        elif len(cells) == 4:
            out[cells[0]] = (cells[2], cells[3])
    return out


HEADER = """# Requirements

Generated by `scripts/seed_requirements.py` from `docs/BRIEF.md` section F. Status and evidence are kept between runs.

Status is `todo`, `in-progress`, `verified`, or `waived (reason, approval)`. A `verified` row names a passing report or a check that could have failed. The verifier column is the gate the contract assigns. A row whose verifier is G4 is not `verified` on a unit test alone.

| ID | Requirement | Verifier | Status | Evidence |
|---|---|---|---|---|
"""


def check() -> int:
    want = {r[0] for r in brief_rows()}
    have = existing()
    bad = 0
    for rid in sorted(want - have.keys()):
        print(f"missing from REQUIREMENTS.md: {rid}")
        bad += 1
    for rid in sorted(have.keys() - want):
        print(f"not in the brief: {rid}")
        bad += 1
    for rid, (status, evidence) in sorted(have.items()):
        if status == "verified" and not evidence:
            print(f"{rid} is verified with no evidence")
            bad += 1
    print(f"requirements: {len(want)} in brief, {len(have)} tracked, {bad} problems")
    return 1 if bad else 0


def write() -> None:
    have = existing()
    lines = [HEADER.rstrip("\n")]
    for rid, req, verifier in brief_rows():
        status, evidence = have.get(rid, ("todo", ""))
        lines.append(f"| {rid} | {req} | {verifier} | {status} | {evidence} |")
    REQS.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    if "--check" in sys.argv:
        sys.exit(check())
    write()
    sys.exit(check())
