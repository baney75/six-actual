using System.Text.Json;

namespace SixActual.Sim.GrandStrategy;

/// <summary>One province of a theater map (data/theaters.json, GS-01).</summary>
public sealed class GsProvinceDef
{
    public string Id { get; init; } = "";

    public string Name { get; init; } = "";

    public int X { get; init; }

    public int Y { get; init; }

    /// <summary>Index into GsRules.Terrains (open, forest, hills, urban).</summary>
    public int Terrain { get; init; }

    public int Owner { get; init; }

    public int Industry { get; init; }

    public int Manpower { get; init; }

    public int[] Neighbours { get; init; } = [];
}

public sealed class GsFactionDef
{
    public string Id { get; init; } = "";

    public string Side { get; init; } = "";

    public int Capital { get; init; }

    public bool AtWar { get; init; }
}

/// <summary>A theater: the factions and provinces of one era (GS-01).</summary>
public sealed class GsTheater
{
    public string Era { get; init; } = "";

    public string[] Sides { get; init; } = [];

    public GsFactionDef[] Factions { get; init; } = [];

    public GsProvinceDef[] Provinces { get; init; } = [];

    public int SideOf(int faction) => Array.IndexOf(Sides, Factions[faction].Side);

    public int ProvinceIndex(string id) => Array.FindIndex(Provinces, p => p.Id == id);

    public int FactionIndex(string id) => Array.FindIndex(Factions, f => f.Id == id);

    public static GsTheater[] Load(string path)
    {
        using var doc = JsonDocument.Parse(File.ReadAllBytes(path));
        var list = new List<GsTheater>();
        foreach (var t in doc.RootElement.GetProperty("theaters").EnumerateArray())
        {
            var factionIds = t.GetProperty("factions").EnumerateArray().Select(f => f.GetProperty("id").GetString()!).ToArray();
            var provinceIds = t.GetProperty("provinces").EnumerateArray().Select(p => p.GetProperty("id").GetString()!).ToArray();
            var factions = t.GetProperty("factions").EnumerateArray().Select(f => new GsFactionDef
            {
                Id = f.GetProperty("id").GetString()!,
                Side = f.GetProperty("side").GetString()!,
                Capital = Array.IndexOf(provinceIds, f.GetProperty("capital").GetString()!),
                AtWar = f.GetProperty("at_war").GetBoolean(),
            }).ToArray();
            list.Add(new GsTheater
            {
                Era = t.GetProperty("era").GetString()!,
                Sides = factions.Select(f => f.Side).Distinct().ToArray(),
                Factions = factions,
                Provinces = t.GetProperty("provinces").EnumerateArray().Select(p => new GsProvinceDef
                {
                    Id = p.GetProperty("id").GetString()!,
                    Name = p.GetProperty("name").GetString()!,
                    X = p.GetProperty("x").GetInt32(),
                    Y = p.GetProperty("y").GetInt32(),
                    Terrain = Array.IndexOf(GsRules.Terrains, p.GetProperty("terrain").GetString()!),
                    Owner = Array.IndexOf(factionIds, p.GetProperty("owner").GetString()!),
                    Industry = p.GetProperty("industry").GetInt32(),
                    Manpower = p.GetProperty("manpower").GetInt32(),
                    Neighbours = p.GetProperty("neighbours").EnumerateArray().Select(n => Array.IndexOf(provinceIds, n.GetString()!)).ToArray(),
                }).ToArray(),
            });
        }

        return list.ToArray();
    }
}

/// <summary>Grand-strategy rules (data/rules.json "grand_strategy"; generated by scripts/generate_rules.py).</summary>
public sealed class GsRules
{
    public static readonly string[] Terrains = ["open", "forest", "hills", "urban"];

    public int TurnLimit { get; init; }

    public int StrengthPerPoint { get; init; }

    public int ArmyMax { get; init; }

    public int StartArmyPerIndustry { get; init; }

    public int ResearchBase { get; init; }

    public int ResearchStep { get; init; }

    public int TechMax { get; init; }

    public int TechBonusPct { get; init; }

    public int[] TerrainDefencePct { get; init; } = [];

    public int CommanderBonusPct { get; init; }

    public int CommanderXpWin { get; init; }

    public int CommanderXpLoss { get; init; }

    public int CommanderWoundPct { get; init; }

    public int CommanderWoundTurns { get; init; }

    public int LossWinnerPct { get; init; }

    public int LossLoserPct { get; init; }

    public int AttritionUnsuppliedPct { get; init; }

    public int LendLeasePct { get; init; }

    public int CeasefireTurns { get; init; }

    public int TensionBattle { get; init; }

    public int TensionCapture { get; init; }

    public int TensionTactical { get; init; }

    public int TensionTheater { get; init; }

    public int TensionStrategic { get; init; }

    public int FalloutTurns { get; init; }

    public int FalloutAttritionPct { get; init; }

    public int TheaterStrikeIndustry { get; init; }

    public int ReinforceTurns { get; init; }

    public int AttackOddsPermille { get; init; }

    public static GsRules Load(string rulesPath)
    {
        using var doc = JsonDocument.Parse(File.ReadAllBytes(rulesPath));
        var g = doc.RootElement.GetProperty("grand_strategy");
        int I(string n) => g.GetProperty(n).GetInt32();
        return new GsRules
        {
            TurnLimit = I("turn_limit"),
            StrengthPerPoint = I("strength_per_point"),
            ArmyMax = I("army_max"),
            StartArmyPerIndustry = I("start_army_per_industry"),
            ResearchBase = I("research_base"),
            ResearchStep = I("research_step"),
            TechMax = I("tech_max"),
            TechBonusPct = I("tech_bonus_pct"),
            TerrainDefencePct = Terrains.Select(t => g.GetProperty("terrain_defence_pct").GetProperty(t).GetInt32()).ToArray(),
            CommanderBonusPct = I("commander_bonus_pct"),
            CommanderXpWin = I("commander_xp_win"),
            CommanderXpLoss = I("commander_xp_loss"),
            CommanderWoundPct = I("commander_wound_pct"),
            CommanderWoundTurns = I("commander_wound_turns"),
            LossWinnerPct = I("loss_winner_pct"),
            LossLoserPct = I("loss_loser_pct"),
            AttritionUnsuppliedPct = I("attrition_unsupplied_pct"),
            LendLeasePct = I("lend_lease_pct"),
            CeasefireTurns = I("ceasefire_turns"),
            TensionBattle = I("tension_battle"),
            TensionCapture = I("tension_capture"),
            TensionTactical = I("tension_tactical"),
            TensionTheater = I("tension_theater"),
            TensionStrategic = I("tension_strategic"),
            FalloutTurns = I("fallout_turns"),
            FalloutAttritionPct = I("fallout_attrition_pct"),
            TheaterStrikeIndustry = I("theater_strike_industry"),
            ReinforceTurns = I("reinforce_turns"),
            AttackOddsPermille = I("attack_odds_permille"),
        };
    }
}
